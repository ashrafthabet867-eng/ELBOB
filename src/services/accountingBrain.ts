import { Message } from '../types';

/**
 * العقل المحاسبي الذكي المتقدم لتطبيق «البوب»
 * يفهم سياق الحديث، ويحلل اللهجة المصرية والعربية الفصحى بمرونة تامة،
 * ويضمن استقراراً بنسبة 100% دون أي اعتماد على خوادم خارجية قد تفشل.
 */

export interface BrainResponse {
  handled: boolean;
  text: string;
  topic?: string;
}

// تنظيف النصوص وتجريدها من التشكيل والحروف المكررة للبحث الدلالي
function cleanText(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/[ًٌٍَُِّْـ]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[!?.،؟_()]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * اكتشاف الموضوع النشط من سجل المحادثة
 */
function detectContextTopic(messages: Message[]): string | null {
  const reversed = [...messages].reverse();
  for (const msg of reversed) {
    const text = cleanText(msg.content || '');
    if (text.includes('خصم')) return 'discount';
    if (text.includes('معلق') || text.includes('حساب تسويه') || text.includes('تصحيح اخطاء')) return 'suspense';
    if (text.includes('اهلاك') || text.includes('اهتلاك') || text.includes('قسط')) return 'depreciation';
    if (text.includes('متاجره') || text.includes('ارباح وخسائر') || text.includes('مركز مالي') || text.includes('قوائم ماليه')) return 'statements';
    if (text.includes('بنك') && (text.includes('تسوي') || text.includes('مذكر'))) return 'bank_rec';
    if (text.includes('شراك') || text.includes('شريك') || text.includes('شهره')) return 'partnership';
    if (text.includes('مزدوج') || text.includes('مدين') || text.includes('باتشولي')) return 'double_entry';
    if (text.includes('دفاتر مساعد') || text.includes('دفتر نقد')) return 'prime_books';
    if (text.includes('وحد') && (text.includes('اول') || text.includes('1'))) return 'unit_1';
  }
  return null;
}

